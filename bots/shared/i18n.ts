export const DICTIONARIES: Record<Locale, BotDictionary> = { en, ru, th, he };

export function getBotDictionary(locale: Locale): BotDictionary {
  return DICTIONARIES[locale] ?? en;
}

/** Looks up a string and fills `{placeholders}`. Params must already be escaped for the output format. */
export function t(locale: Locale, key: DictKey, params: Record<string, string | number> = {}): string {
  const template = getBotDictionary(locale)[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

