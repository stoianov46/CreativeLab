export const getPrimaryNav = memo((locale): NavItem[] => {
  const ui = getUi(locale);
  const link = (href: string, fallback = href) => ({ label: pageLabelFor(href, locale) ?? fallback, href });
  return [
    {
      label: ui.nav.services,
      href: "/services",
      groups: SERVICE_GROUPS.map((group) => ({
        title: ui.nav.serviceGroups[group.key],
        items: group.hrefs.map((href) => link(href)),
      })),
    },
    {
      label: ui.nav.industries,
      href: "/industries",
      children: getIndustries(locale).map((page) => ({ label: page.navLabel, href: `/industries/${page.slug}` })),
    },
    {
      label: ui.nav.locations,
      href: "/locations",
      children: getLocations(locale).map((page) => ({ label: page.navLabel, href: `/locations/${page.slug}` })),
    },
    {
      label: ui.nav.work,
      href: "/portfolio",
      children: [
        { label: ui.nav.portfolio, href: "/portfolio" },
        { label: ui.nav.caseStudies, href: "/case-studies" },
      ],
    },
    { label: ui.nav.journal, href: "/journal" },
    { label: ui.nav.about, href: "/about" },
    { label: ui.nav.contact, href: "/contact" },
  ];
});

