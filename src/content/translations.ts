/**
 * The localized name of the page an internal href points at — lets
 * cross-links (menu, related services, cards) show the page's own current
 * name instead of a copy of it that could drift.
 */
export function pageLabelFor(href: string, locale: Locale): string | undefined {
  const [, first, second] = href.split("/");
  const find = <T extends { slug: string; navLabel: string }>(list: T[]) =>
    list.find((page) => page.slug === second)?.navLabel;
  if (first === "services" && second) return find(getServiceLandings(locale));
  if (first === "industries" && second) return find(getIndustries(locale));
  if (first === "locations" && second) return find(getLocations(locale));
  const hub = getHub(first ?? "", locale);
  if (!hub) return undefined;
  if (!second) return hub.navLabel;
  return hub.services.find((s) => s.slug === second)?.navLabel;
}
