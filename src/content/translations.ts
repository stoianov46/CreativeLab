/**
 * Every translation file and the English it overlays, keyed by its path
 * under `src/content/locales/<locale>/`. Single source of truth for both the
 * site (below) and `scripts/i18n.mjs` (check/sync/pending/accept/export).
 */
export const TRANSLATION_SOURCES: Record<string, unknown> = {
  "ui.json": UI,
  "pages.json": PAGES,
  "case-studies.json": CASE_STUDIES,
  "journal.json": ARTICLES,
  ...Object.fromEntries(HUBS.map((hub) => [`hubs/${hub.slug}.json`, hub])),
  ...Object.fromEntries(SERVICE_LANDINGS.map((page) => [`services/${page.slug}.json`, page])),
  ...Object.fromEntries(INDUSTRIES.map((page) => [`industries/${page.slug}.json`, page])),
  ...Object.fromEntries(LOCATIONS.map((page) => [`locations/${page.slug}.json`, page])),
};

function memo<T>(build: (locale: Locale) => T): (locale: Locale) => T {
  const cache = new Map<Locale, T>();
  return (locale) => {
    if (!cache.has(locale)) cache.set(locale, build(locale));
    return cache.get(locale)!;
  };
}

function overlay(locale: Locale, file: string): unknown {
  if (locale === DEFAULT_LOCALE) return undefined;
  return TRANSLATIONS[locale as Exclude<Locale, "en">].files[file];
}

export const getUi = memo((locale): UiStrings => localize(UI, overlay(locale, "ui.json")));

export const getPages = memo((locale): typeof PAGES => localize(PAGES, overlay(locale, "pages.json")));

export const getHubs = memo((locale): HubPage[] =>
  HUBS.map((hub) => localize(hub, overlay(locale, `hubs/${hub.slug}.json`)))
);

export const getServiceLandings = memo((locale): ServicePage[] =>
  SERVICE_LANDINGS.map((page) => localize(page, overlay(locale, `services/${page.slug}.json`)))
);

export const getIndustries = memo((locale): IndustryPage[] =>
  INDUSTRIES.map((page) => localize(page, overlay(locale, `industries/${page.slug}.json`)))
);

export const getLocations = memo((locale): LocationPage[] =>
  LOCATIONS.map((page) => localize(page, overlay(locale, `locations/${page.slug}.json`)))
);

export const getCaseStudies = memo((locale): CaseStudy[] =>
  localize(CASE_STUDIES, overlay(locale, "case-studies.json"))
);

export const getArticles = memo((locale): Article[] =>
  localize(ARTICLES, overlay(locale, "journal.json"))
);

export function getHub(slug: string, locale: Locale): HubPage | undefined {
  return getHubs(locale).find((hub) => hub.slug === slug);
}

export function getService(
  hubSlug: string,
  serviceSlug: string,
  locale: Locale
): { hub: HubPage; service: ServicePage } | undefined {
  const hub = getHub(hubSlug, locale);
  const service = hub?.services.find((s) => s.slug === serviceSlug);
  return hub && service ? { hub, service } : undefined;
}

