/** Shape of `src/content/locales/<locale>/index.ts` (generated by `npm run i18n:sync`). */
type LocaleTranslations = { files: Record<string, unknown> };

const TRANSLATIONS: Record<Exclude<Locale, "en">, LocaleTranslations> = { ru, th, he };

